#!/usr/bin/env python3
"""
Phase 2 T3: resolve the x86-64 Debian (bookworm, main) package set that Box64 needs
as runtime DATA for Xvfb + wine + small GUI apps, and emit runtime-libs.lock:
  url <bytes> <sha256-to-be-filed-at-download>
Only packages box64 does NOT wrap are needed (libc etc. stay wrapped). The X11/Xorg
and freetype families are explicitly needed because on Android there is no host copy
for box64's wrappers to bind to.

Run once on the laptop (WSL); the lock file goes into the APK as an asset, and the
phone-side harness action downloads from the pinned URLs and re-hashes every file.
"""
import gzip, io, sys, urllib.request, re

MIRROR = "https://deb.debian.org/debian"
SUITE = "bookworm"
ARCH = "amd64"
# dep -> version constraints are stripped; alternatives split by '|'
ROOTS = ["xvfb", "x11-apps", "xfonts-base", "libfontconfig1", "libfreetype6"]
# Never pull these (wrapped by box64 / not needed on Android) - keep the libc6
# family IN: on Android Box64's bionic wrapper cannot supply glibc symbols
# (__errno_location, __ctype_b_loc, ...) so the guest needs the emulated glibc.
EXCLUDE = {"libc-bin", "gcc-12-base", "debconf", "dpkg",
           "lsb-base", "init-system-helpers", "sysvinit-utils", "mount",
           "coreutils", "util-linux", "passwd", "bsdutils", "adduser",
           "xorg-server-common", "man-db", "groff-base", "groff", "manpages",
           "bsdextrautils", "bsdmainutils", "manpages-dev", "xz-utils",
           "tar", "grep", "sed", "findutils", "file", "diffutils", "mawk",
           "gawk", "gzip", "hostname", "netbase", "perl", "perl-base",
           "libperl5.36", "ucf", "sensible-utils"}
# NOTE: dash is deliberately NOT excluded (this project): guest posix tools and
# the X server popen /bin/sh (keymap compilation), so a real guest shell is needed.

def slimDeps(s):
    # "libc6 (>= 2.34), x11-common (>= ...)" -> names
    out = set()
    for group in re.split(r"\s*,\s*", s.strip()):
        first = re.split(r"\s*\|\s*", group)[0]
        name = re.match(r"([A-Za-z0-9.+-]+)", first.strip())
        if name:
            out.add(name.group(1))
    return out

def fetch_packages():
    url = f"{MIRROR}/dists/{SUITE}/main/binary-{ARCH}/Packages.xz"
    print("fetching", url)
    import lzma
    raw = urllib.request.urlopen(url, timeout=120).read()
    data = lzma.decompress(raw)
    pkgs = {}
    cur = {}
    for line in data.decode("utf-8", "replace").split("\n"):
        if not line.strip():
            if cur.get("Package"):
                pkgs[cur["Package"]] = cur
            cur = {}
        elif line.startswith(" "):
            pass
        else:
            k, _, v = line.partition(": ")
            cur[k] = v
    if cur.get("Package"):
        pkgs[cur["Package"]] = cur
    return pkgs

def main():
    pkgs = fetch_packages()
    todo = [r for r in ROOTS if r in pkgs]
    need, missing = set(), []
    seen = list(todo)
    while seen:
        p = seen.pop(0)
        if p in need or p in EXCLUDE:
            continue
        if p not in pkgs:
            missing.append(p); continue
        need.add(p)
        cur = pkgs[p]
        deps = set()
        for f in ("Depends", "Pre-Depends"):
            if f in cur:
                deps |= slimDeps(cur[f])
        for d in sorted(deps):
            if d not in need:
                seen.append(d)
    lines = []
    for name in sorted(need):
        cur = pkgs[name]
        fname = cur["Filename"]
        size = cur.get("Size", "?")
        sha = cur.get("SHA256", "?")
        lines.append(f"{MIRROR}/{fname} {size} {sha} {name}")
    out = "/mnt/c/Users/Asus/Documents/GitHub/unified-desktop/android/win86/runtime-libs.lock"
    with open(out, "w") as f:
        f.write(f"# generated by resolve-runtime-libs.py; Debian {SUITE} main {ARCH}\n")
        f.write(f"# {len(lines)} packages\n")
        f.write("\n".join(lines) + "\n")
    print("missing:", sorted(set(missing)))
    print("wrote", out, len(lines), "packages")
    for l in lines[:8]:
        print(" ", l)
    if missing:
        print("MISSING (debug):", missing)
        return 2
    return 0

sys.exit(main())
